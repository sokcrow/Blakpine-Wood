/* Forest Horror: unión de zonas manuales. No modifica mapas al cargarlos. */
(function (root, factory) {
  const api = factory();
  if (root) root.FHAreaMerge = api;
  if (typeof module === 'object' && module.exports) module.exports = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
  const TYPES = new Set([
    'hall', 'outside', 'building', 'pavement', 'parking', 'grass', 'dirt',
    'asphalt', 'alley', 'sidewalk', 'concrete', 'gravel', 'cobblestone',
    'tile_floor', 'carpet', 'wood_floor'
  ]);
  const EPS = 1e-6;
  const GEOMETRY = new Set(['id', 'x', 'y', 'w', 'h', 'spans', 'mergedFromIds']);
  const DEFAULTS = {label:'', apartmentId:'', roomId:'', zoneId:'main', ownerId:'', blocksViewOutside:false};
  const rects = item => item.spans?.length ? item.spans : [{x:item.x,y:item.y,w:item.w,h:item.h}];
  const valid = r => [r.x,r.y,r.w,r.h].every(Number.isFinite) && r.w>EPS && r.h>EPS;
  const round = v => Math.round(v*1e6)/1e6;

  function compatible(a,b) {
    if (!TYPES.has(a.type) || a.type !== b.type || a.autoGenerated || b.autoGenerated) return false;
    if (a.cells?.length || b.cells?.length) return false;
    const keys = new Set([...Object.keys(a), ...Object.keys(b), ...Object.keys(DEFAULTS)]);
    for (const key of keys) {
      if (GEOMETRY.has(key)) continue;
      if (JSON.stringify(a[key] ?? DEFAULTS[key] ?? null) !== JSON.stringify(b[key] ?? DEFAULTS[key] ?? null)) return false;
    }
    return true;
  }

  function connected(a,b) {
    const ox = Math.min(a.x+a.w,b.x+b.w)-Math.max(a.x,b.x);
    const oy = Math.min(a.y+a.h,b.y+b.h)-Math.max(a.y,b.y);
    return (ox>EPS && oy>=-EPS) || (oy>EPS && ox>=-EPS);
  }

  // Barrido vertical: unión exacta de rectángulos sin rellenar los huecos de una L.
  function union(rectangles) {
    const source = rectangles.filter(valid);
    if (!source.length) return [];
    const xs = [...new Set(source.flatMap(r=>[r.x,round(r.x+r.w)]))].sort((a,b)=>a-b);
    const output = [];
    for (let i=0;i<xs.length-1;i++) {
      const x=xs[i],right=xs[i+1];
      if (right-x<=EPS) continue;
      const intervals=source.filter(r=>r.x<=x+EPS&&r.x+r.w>=right-EPS)
        .map(r=>[r.y,r.y+r.h]).sort((a,b)=>a[0]-b[0]);
      const vertical=[];
      for (const pair of intervals) {
        const last=vertical[vertical.length-1];
        if (last && pair[0]<=last[1]+EPS) last[1]=Math.max(last[1],pair[1]);
        else vertical.push([...pair]);
      }
      for (const [top,bottom] of vertical) {
        const previous=output.find(r=>Math.abs(r.x+r.w-x)<EPS&&Math.abs(r.y-top)<EPS&&Math.abs(r.y+r.h-bottom)<EPS);
        if (previous) previous.w=round(right-previous.x);
        else output.push({x:round(x),y:round(top),w:round(right-x),h:round(bottom-top)});
      }
    }
    return output.sort((a,b)=>a.y-b.y||a.x-b.x);
  }

  function merge(items, incoming) {
    if (!TYPES.has(incoming?.type) || !rects(incoming).every(valid))
      return {items, zone:incoming, merged:0};
    const absorbed=new Set(), group=[incoming];
    let again=true;
    while (again) {
      again=false;
      for (const existing of items) {
        if (absorbed.has(existing) || !compatible(incoming,existing) || !rects(existing).every(valid)) continue;
        if (rects(existing).some(a=>group.some(g=>rects(g).some(b=>connected(a,b))))) {
          absorbed.add(existing);group.push(existing);again=true;
        }
      }
    }
    if (!absorbed.size) return {items, zone:incoming, merged:0};
    const pieces=union(group.flatMap(rects));
    const left=Math.min(...pieces.map(r=>r.x)),top=Math.min(...pieces.map(r=>r.y));
    const right=Math.max(...pieces.map(r=>r.x+r.w)),bottom=Math.max(...pieces.map(r=>r.y+r.h));
    const original=[...absorbed][0];
    const zone={...incoming,id:original.id,x:left,y:top,w:round(right-left),h:round(bottom-top)};
    if (pieces.length>1) zone.spans=pieces;
    else delete zone.spans;
    zone.mergedFromIds=[...new Set(group.flatMap(g=>[g.id,...(g.mergedFromIds||[])]))].filter(id=>id!==zone.id);
    return {items:items.filter(it=>!absorbed.has(it)).concat(zone),zone,merged:absorbed.size};
  }

  // El motor original dibuja superficies rectangulares; solo se expanden en la vista 3D.
  function forEngine(items) {
    return items.flatMap(it=>TYPES.has(it.type)&&it.spans?.length
      ?it.spans.map((sp,i)=>{const part={...it,...sp,id:it.id+'_part_'+i};delete part.spans;delete part.mergedFromIds;return part;})
      :[it]);
  }
  return Object.freeze({merge,forEngine,union,connected,compatible});
});
