const assert=require('node:assert/strict');
const M=require('./fh-area-merge.js');
const zone=(id,x,y,w,h,overrides={})=>({id,type:'hall',label:'Pasillo',apartmentId:'',roomId:'',x,y,w,h,...overrides});
const area=parts=>parts.reduce((sum,s)=>sum+s.w*s.h,0);
let checks=0;const test=(desc,fn)=>{fn();checks++;console.log('OK',desc)};
test('Unión de dos zonas con borde compartido',()=>{
 const x=M.merge([zone('a',0,0,2,2)],zone('b',2,0,2,2));
 assert.equal(x.items.length,1);assert.equal(x.zone.id,'a');assert.equal(x.zone.w,4);assert.equal(x.merged,1);
});
test('Superposición sin área duplicada',()=>{
 const x=M.merge([zone('a',0,0,3,2)],zone('b',1,0,3,2));
 assert.equal(area(x.zone.spans||[x.zone]),8);
});
test('Forma en L no cubre espacios que no pertenecen',()=>{
 const x=M.merge([zone('a',0,0,4,1)],zone('b',3,1,1,3));
 assert.equal(area(x.zone.spans),7);assert.equal(x.zone.w*x.zone.h,16);
 const d=M.forEngine(x.items);assert.equal(area(d),7);
});
test('Una esquina puntual no fusiona zonas',()=>{
 const x=M.merge([zone('a',0,0,1,1)],zone('b',1,1,1,1));assert.equal(x.merged,0);
});
test('No fusiona distintos propietarios o superficies',()=>{
 assert.equal(M.merge([zone('a',0,0,1,1,{ownerId:'alice'})],zone('b',1,0,1,1,{ownerId:'bob'})).merged,0);
 assert.equal(M.merge([zone('a',0,0,1,1,{surfaceStyle:{preset:'asfalto'}})],zone('b',1,0,1,1,{surfaceStyle:{preset:'baldosa'}})).merged,0);
});
test('Zona nueva que conecta otras dos las convierte en una',()=>{
 const x=M.merge([zone('a',0,0,1,1),zone('c',2,0,1,1)],zone('b',1,0,1,1));assert.equal(x.merged,2);assert.equal(x.items.length,1);assert.equal(x.zone.w,3);
});
test('La geometría original y los IDs de entrada se conservan',()=>{
 const before=zone('a',0,0,2,2),next=zone('b',2,0,1,1);M.merge([before],next);assert.equal(before.id,'a');assert.equal(before.w,2);assert.equal(next.id,'b');
});
test('Áreas automáticas y tipos distintos no se fusionan',()=>{
 assert.equal(M.merge([zone('a',0,0,1,1,{autoGenerated:true})],zone('b',1,0,1,1)).merged,0);
 assert.equal(M.merge([zone('a',0,0,1,1,{type:'sidewalk'})],zone('b',1,0,1,1)).merged,0);
});
console.log(checks+' pruebas correctas');
