/* Blakpine-Wood · Drenajes 05. Accesos verticales con el motor de niveles existente.
 * No crea colisiones ni transiciones de piso paralelas.
 */
(function(root,factory){
 'use strict';
 const api=factory(root);
 if(typeof module==='object'&&module.exports)module.exports=api;
 if(root)root.FHDrainageAccess=api;
})(typeof globalThis!=='undefined'?globalThis:this,function(root){
 'use strict';
 const EPS=1e-5,RAIN_LENGTH=.48,PARTICLES=6;
 const isAccess=it=>it?.type==='drain_access'&&it.drainageAccess?.version===1;
 const finite=n=>typeof n==='number'&&Number.isFinite(n);
 const inside=(s,p)=>p.x>=s.x&&p.y>=s.y&&p.x<s.x+s.w&&p.y<s.y+s.h;
 const center=it=>({x:it.x,y:it.y});
 const distance=(a,b)=>Math.hypot(a.x-b.x,a.y-b.y);
 const drain=()=>root?.FHDrainage;
 const floorById=(map,id)=>(map?.floors||[]).findIndex(f=>String(f.id)===String(id));
 const mainIndex=map=>{
  const fromId=floorById(map,map?.mainFloorId);
  return fromId>=0?fromId:(map?.floors||[]).findIndex(f=>Number(f.elevationFt)===0);
 };
 const doorNear=(floor,p)=>!!(floor?.items||[]).find(it=>
  ['door','peephole_door','opening'].includes(it.type)&&it.a&&it.b&&(()=>{
   const a=it.a,b=it.b,dx=b.x-a.x,dy=b.y-a.y,len=dx*dx+dy*dy;
   const t=len?Math.max(0,Math.min(1,((p.x-a.x)*dx+(p.y-a.y)*dy)/len)):0;
   return Math.hypot(p.x-a.x-t*dx,p.y-a.y-t*dy)<=2.2;
  })());
 function safeLanding(map,f,at,allowed){
  const p={x:Math.floor(at.x)+.5,y:Math.floor(at.y)+.5};
  const section=(map?.floors?.[f]?.items||[]).find(it=>drain()?.isSection(it)&&inside(it,p));
  if(!section)return null;
  const all=[];
  for(let y=Math.ceil(section.y);y<section.y+section.h;y++)for(let x=Math.ceil(section.x);x<section.x+section.w;x++){
   const point={x:x+.5,y:y+.5};
   if(drain().waterAt(map,f,point,0)||allowed&&!allowed(point))continue;
   all.push(point);
  }
  all.sort((a,b)=>distance(a,p)-distance(b,p)||a.y-b.y||a.x-b.x);
  return all.length?{point:all[0],section}:null;
 }
 function makePair(map,fromIndex,at,kind,newId){
  if(!['street','building'].includes(kind))throw Error('Tipo de entrada al drenaje inválido.');
  const upper=map?.floors?.[fromIndex],lower=map?.floors?.[fromIndex-1];
  if(!upper||!lower||!(Number(upper.elevationFt)>Number(lower.elevationFt)))
   throw Error('Primero crea un nivel inferior contiguo con drenajes.');
  if(kind==='street'&&fromIndex!==mainIndex(map))throw Error('El respiradero de calle se coloca en planta baja.');
  if(!at||!finite(at.x)||!finite(at.y))throw Error('Posición del acceso inválida.');
  const landing=safeLanding(map,fromIndex-1,at,kind==='building'?p=>doorNear(upper,p):null);
  if(!landing)throw Error(kind==='building'?'Para acceder desde un edificio coloca una puerta o hueco junto al acceso.':
   'Coloca el acceso encima de un tramo de drenaje del piso inferior.');
  const p=landing.point;
  if(kind==='street'&&(upper.items||[]).some(it=>it.type==='room'&&inside(it,p)))
   throw Error('El respiradero de calle no puede situarse dentro de una habitación.');
  const occupied=(f)=>(map.floors[f]?.items||[]).some(it=>isAccess(it)&&distance(it,p)<.75);
  if(occupied(fromIndex)||occupied(fromIndex-1))throw Error('Ya existe un acceso en esa posición.');
  const id1=String(newId()),id2=String(newId());
  if(id1===id2||[...map.floors.flatMap(f=>f.items||[])].some(it=>it.id===id1||it.id===id2))
   throw Error('Los identificadores de accesos deben ser únicos.');
  const item=(id,role,toFloor,toId)=>({
   id,type:'drain_access',x:p.x,y:p.y,w:.85,h:.85,rotation:0,
   blocksMovement:false,heightFt:0,autoGenerated:false,
   drainageAccess:{version:1,kind:role,targetFloorId:toFloor.id,targetItemId:toId,
    sectionId:landing.section.id},
   interact:{id:'drain_access_'+id,verb:'use',label:role==='sewer'?'Subir por acceso de drenaje':'Bajar al drenaje',effects:[]}
  });
  return {source:item(id1,kind,lower,id2),destination:item(id2,'sewer',upper,id1),
   sourceIndex:fromIndex,destinationIndex:fromIndex-1,sectionId:landing.section.id};
 }
 function resolve(map,fromIndex,item){
  if(!isAccess(item))return null;
  const targetIndex=floorById(map,item.drainageAccess.targetFloorId);
  if(targetIndex<0||targetIndex===fromIndex)return null;
  const target=(map.floors[targetIndex]?.items||[]).find(it=>isAccess(it)&&
   String(it.id)===String(item.drainageAccess.targetItemId));
  if(!target||String(target.drainageAccess.targetFloorId)!==String(map.floors[fromIndex]?.id)||
   String(target.drainageAccess.targetItemId)!==String(item.id)||
   distance(item,target)>EPS)return null;
  const top=fromIndex>targetIndex?item:target,low=fromIndex>targetIndex?target:item;
  const lowerIndex=Math.min(fromIndex,targetIndex),upperIndex=Math.max(fromIndex,targetIndex);
  if(upperIndex!==lowerIndex+1||low.drainageAccess.kind!=='sewer'||!['street','building'].includes(top.drainageAccess.kind))return null;
  const lower=map.floors[lowerIndex],section=(lower.items||[]).find(s=>
   drain()?.isSection(s)&&String(s.id)===String(low.drainageAccess.sectionId)&&inside(s,center(low)));
  if(!section||drain().waterAt(map,lowerIndex,center(low),0))return null;
  if(top.drainageAccess.kind==='street'&&upperIndex!==mainIndex(map))return null;
  if(top.drainageAccess.kind==='building'&&!doorNear(map.floors[upperIndex],center(top)))return null;
  return {floorIndex:targetIndex,item:target,x:target.x,y:target.y,
   source:top,section,kind:top.drainageAccess.kind};
 }
 function validateProject(map){
  for(let f=0;f<(map?.floors||[]).length;f++)for(const it of map.floors[f].items||[]){
   if(it.type!=='drain_access')continue;
   if(!isAccess(it)||!finite(it.x)||!finite(it.y)||it.blocksMovement!==false||
    !finite(it.w)||!finite(it.h)||it.x<0||it.y<0||
    it.x>(map.units?.columns||120)||it.y>(map.units?.rows||120)||
    !resolve(map,f,it))throw Error('Acceso de drenaje sin vínculo válido: '+String(it.id||''));
  }
  return true;
 }
 function canNpcUse(item,npc,{flooded=false}={}){
  const flags=npc?.capabilities||npc||{};
  return isAccess(item)&&flags.canEnterDrainage===true&&(!flooded||flags.canSwim===true);
 }
 function lightSources(map,floorIndex,minutes,weather,outdoors){
  const floor=map?.floors?.[floorIndex];if(!floor)return [];
  const sun=root?.FHNaturalLight?.lightAt?.(minutes||0)?.sun||0;
  const sky=Math.max(0,Math.min(1,sun))*Math.max(0,Math.min(1,Number(weather?.light??1)));
  if(sky<=.04)return [];
  const cellFt=Number(map?.units?.feetPerCell)||5;
  const bright=5/cellFt,dim=10/cellFt;
  return (floor.items||[]).filter(it=>isAccess(it)&&it.drainageAccess.kind==='sewer')
   .flatMap(it=>{
    const link=resolve(map,floorIndex,it);
    if(!link||link.kind!=='street')return [];
    const upperIndex=link.floorIndex;
    if(typeof outdoors==='function'&&!outdoors(upperIndex,it.x,it.y))return [];
    return [{x:it.x,y:it.y,bright,range:dim,strength:sky,sourceFloor:upperIndex}];
   });
 }
 function draw2D(ctx,items,toPixel,gx,gy,selection){
  for(const it of items||[])if(isAccess(it)){
   const p=toPixel(it),side=Math.max(5,Math.min(gx,gy)*.8),x=p.x,y=p.y;
   ctx.save();ctx.fillStyle=it.drainageAccess.kind==='sewer'?'#49636c':'#6e7979';
   ctx.fillRect(x-side/2,y-side/2,side,side);
   ctx.strokeStyle=it.id===selection?'#ffe6a5':'#c1d3d1';
   ctx.lineWidth=Math.max(1,Math.min(gx,gy)*.07);
   ctx.strokeRect(x-side/2,y-side/2,side,side);
   for(let k=-1;k<=1;k++){ctx.beginPath();ctx.moveTo(x+side*k/4,y-side*.4);ctx.lineTo(x+side*k/4,y+side*.4);ctx.stroke();}
   ctx.restore();
  }
 }
 const visuals=[];
 function attachFloor(THREE,map,story,index,CELL){
  for(const it of map.floors[index]?.items||[])if(isAccess(it)){
   const metal=new THREE.MeshLambertMaterial({color:it.drainageAccess.kind==='sewer'?0x567983:0x687b78});
   const dark=new THREE.MeshBasicMaterial({color:0x131e21});
   const x=it.x*CELL,z=it.y*CELL;
   const box=(material,px,py,pz,w,h,d)=>{
    const mesh=new THREE.Mesh(new THREE.BoxGeometry(w,h,d),material);
    mesh.position.set(px,py,pz);story.add(mesh);return mesh;
   };
   box(dark,x,.046,z,.8*CELL,.036,.8*CELL);
   box(metal,x,.085,z,.85*CELL,.055,.08*CELL);
   box(metal,x,.085,z,.08*CELL,.055,.85*CELL);
   for(const offset of [-.31,-.16,0,.16,.31])box(metal,x+offset*CELL,.099,z,.026*CELL,.027,.78*CELL);
   const rain=[];
   const exposedSewer=it.drainageAccess.kind==='sewer'&&resolve(map,index,it)?.kind==='street';
   let light=null;
   if(exposedSewer&&typeof THREE.PointLight==='function'){
    light=new THREE.PointLight(0xc9e7f0,0,2*CELL,1.8);
    light.position.set(x,1.85,z);light.castShadow=false;story.add(light);
   }
   if(exposedSewer){
    const water=new THREE.MeshBasicMaterial({color:0x9bc4da,transparent:true,opacity:.68,depthWrite:false});
    for(let k=0;k<PARTICLES;k++){
     const px=x+((k%3)-1)*.18*CELL,pz=z+(Math.floor(k/3)-.5)*.27*CELL;
     const drop=box(water,px,1.6+k*.12,pz,.013*CELL,RAIN_LENGTH,.013*CELL);
     drop.visible=false;rain.push(drop);
    }
   }
   visuals.push({floorIndex:index,item:it,rain,light,clock:0});
  }
 }
 function updateVisuals(dt,weather,map,outdoors,minutes){
  const delta=Math.max(0,Math.min(.08,Number(dt)||0));
  const rainy=weather?.phase==='lluvia'&&Number(weather.intensity)>0;
  const sun=Math.max(0,Number(root?.FHNaturalLight?.lightAt?.(minutes??weather?.clock?.minutes??0)?.sun)||0);
  const daylight=sun*Math.max(0,Math.min(1,Number(weather?.light??1)));
  for(const v of visuals){
   if(!v.rain.length)continue;
   const link=resolve(map,v.floorIndex,v.item);
   const exposed=link&&(!outdoors||outdoors(link.floorIndex,v.item.x,v.item.y));
   if(v.light)v.light.intensity=exposed?daylight*1.45:0;
   v.clock=(v.clock+delta*(rainy?1+Number(weather.intensity):1))%1;
   for(let i=0;i<v.rain.length;i++){
    const drop=v.rain[i];drop.visible=!!(rainy&&exposed);
    drop.position.y=.35+((v.clock+i/PARTICLES)%1)*1.8;
   }
  }
 }
 return Object.freeze({isAccess,makePair,resolve,validateProject,canNpcUse,lightSources,
  draw2D,attachFloor,updateVisuals});
});
