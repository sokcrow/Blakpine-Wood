test('cambiar PB → B1 por PB → P1 o borrar limpia tramo anterior y enlaza subida',()=>{
 const p=sample(),sync=getSync(p);
 sync();
 const human=p.floors[1].items[0];
 human.targetFloorId='p1';human.stairDirection='up';delete human.linkedSourceId;
 sync();
 assert.equal(p.floors[0].items.length,0,'B1 no retiene escaleras huérfanas');
 assert.equal(p.floors[2].items.length,1,'P1 recibe marcador de bajada del tramo ascendente');
 assert.equal(p.floors[2].items[0].autoLanding,true);
 p.floors[1].items=[];sync();
 assert.equal(p.floors[2].items.length,0,'borrar la fuente borra su enlace');
});

test('en mapas antiguos, el destino explícito inferior activa la pareja sin migración del esquema',()=>{
 const p=sample();delete p.floors[1].items[0].stairDirection;
 const sync=getSync(p);sync();
 assert.equal(p.floors[1].items[0].stairDirection,'down');
 assert.equal(p.floors[0].items.length,1);
 assert.equal(p.schema,'forest-horror-map-v1');
 assert.equal(L.sortByElevation(p).ok,true,'ordenar un edificio con bajada válida no queda bloqueado');
 assert.equal(L.insert(p,'b1','below',{id:'b2',elevationFt:0,items:[]}).ok,true,'agregar B2 no cruza el enlace B1-PB');
 assert.equal(L.reorder(p,'pb','down').ok,false,'no se puede invertir una escalera conectada');
});

test('motor 3D convierte SOLO en memoria la bajada PB a media escalera descendente',()=>{
 const source=patchedEngine();
 const begin=source.indexOf('// Las escaleras colocadas ARRIBA para bajar usan');
 const end=source.indexOf('// Cada escalera reserva su abertura',begin);
 assert.ok(begin>=0&&end>begin);
 const normalizer=new Function('DATA','ForestShared',source.slice(begin,end));
 const p=sample(),sync=getSync(p);sync();
 const serialized=JSON.stringify(p),runtime=JSON.parse(serialized);
 const marker=a=>({x:a.x,y:a.y-1,w:a.w,h:a.h/2,rotation:a.rotation});
 normalizer(runtime,{stairDownMarker:marker});
 const high=runtime.floors[1].items[0],lower=runtime.floors[0].items[0];
 assert.equal(high.autoLanding,true,'PB se dibuja como entrada superior descendente');
 assert.equal(high.targetFloorId,'b1');
 assert.equal(high.linkedSourceId,lower.id);
 assert.equal(high.h,lower.h/2,'la entrada PB es media escalera');
 assert.equal(lower.autoLanding,undefined,'B1 posee el tramo completo ascendente');
 assert.equal(lower.targetFloorId,'pb');
 assert.equal(JSON.stringify(p),serialized,'el JSON exportado conserva la fuente editable');
 assert.match(source,/part\(MAT\.wood,0,-rise\*\(1-progress\)/,'la entrada se dibuja bajo el nivel PB');
 assert.match(source,/const top=rise\*\(i\+1\)\/count;/,'la subida física nace en el piso inferior');
 assert.match(source,/stairVoids\[i\+1\]\.push\(stairVoidFor\(item,i\)\)/,'PB tendrá su hueco de escalera');
 assert.match(source,/const isBuilt=DATA\.floors\.map/);
});

test('motor 3D recupera una bajada sin tramo espejo, sin teletransportar a una subida falsa',()=>{
 const source=patchedEngine();
 const a=source.indexOf('// Las escaleras colocadas ARRIBA para bajar usan'),b=source.indexOf('// Cada escalera reserva',a);
 const normalize=new Function('DATA','ForestShared',source.slice(a,b));
 const p=sample();
 normalize(p,{stairDownMarker:st=>({x:st.x,y:st.y-1,w:st.w,h:st.h/2,rotation:st.rotation})});
 assert.equal(p.floors[0].items.length,1);
 assert.equal(p.floors[0].items[0].autoDescendingSource,true);
 assert.equal(p.floors[1].items[0].autoLanding,true);
 assert.equal(p.floors[1].items[0].linkedSourceId,p.floors[0].items[0].id);
});

