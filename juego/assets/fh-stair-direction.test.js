'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const L=require('./fh-floor-levels.js');
const html=()=>fs.readFileSync(path.join(__dirname,'../../index.html'),'utf8');
const stair=(id,targetFloorId)=>({id,type:'stairs',x:8,y:10,w:.5,h:3.5,rotation:90,
 targetFloorId,label:'Escalera ↓ a B1',stairDirection:'down',heightFt:10});
const sample=()=>({schema:'forest-horror-map-v1',mainFloorId:'pb',floors:[
 {id:'b1',name:'Sótano',elevationFt:-10,items:[]},
 {id:'pb',name:'Planta baja',elevationFt:0,items:[stair('down_pb','b1')]},
 {id:'p1',name:'Planta alta',elevationFt:10,items:[]}
]});
function getSync(project){
 const doc=html(),start=doc.indexOf('function syncStairLinks(){');
 const end=doc.indexOf('function syncPropertyDoorRoles(){',start);
 assert.ok(start>0&&end>start,'existe sincronización real de escaleras');
 let n=0;
 const fakeShared={stairDownMarker:src=>({
  x:src.x,y:src.y-1,w:src.w,h:src.h*.5,rotation:src.rotation
 })};
 return new Function('project','ForestShared','numId',
  doc.slice(start,end)+'\nreturn syncStairLinks;'
 )(project,fakeShared,()=>('auto_'+(++n)));
}
function engine(){
 const files=Array.from({length:13},(_,i)=>'engine-'+String(i).padStart(2,'0')+'.js');
 const encoded=files.map(name=>{
  const raw=fs.readFileSync(path.join(__dirname,name),'utf8');
  return raw.slice(raw.indexOf('+"')+2,raw.lastIndexOf('";'));
 }).join('');
 return Buffer.from(encoded,'base64').toString('utf8');
}
function patchedEngine(){
 const doc=html(),a=doc.indexOf('function addBuildingLevelsToEngine(doc){');
 const b=doc.indexOf('// Restringe las fachadas de niveles vecinos',a);
 assert.ok(a>=0&&b>a);
 const patch=new Function('return ('+doc.slice(a,b).trim()+')')();
 return patch(engine());
}

