const assert=require('node:assert/strict');
require('./fh-survival-core.js');
const S=require('./fh-skills.js');
assert.equal(S.IDS.length,32);
assert.equal(new Set(S.IDS).size,32);
assert.deepEqual(Object.keys(S.GROUPS),['FOR','AGI','VOL','PRU','ING','ARC','SOC']);
const char={skills:S.emptyPoints()};
assert.equal(S.readPoints(char,'informatica'),0);
assert.equal(S.setPoints(char,'informatica',4),4);
assert.equal(S.readPoints(char,'informatica'),4);
assert.deepEqual(S.normalizePoints({informatica:3,percepcion:-1,unknown:99}).informatica,3);
assert.equal(S.normalizePoints({informatica:3,percepcion:-1,unknown:99}).percepcion,0);
assert.equal(S.normalizePoints({informatica:3,percepcion:-1,unknown:99}).unknown,undefined);
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,a+' != '+b);
let o=S.odds({skills:{informatica:2}},'informatica',{difficulty:6});
near(o.headsPercent,50);near(o.successPercent,50);
o=S.odds(char,'informatica',{difficulty:9,advantage:1});
near(o.headsPercent,30);near(o.successPercent,51);
near(o.criticalSuccessPercent,9);near(o.criticalFailurePercent,49);
o=S.odds(char,'informatica',{difficulty:9,advantage:1,disadvantage:1});
assert.equal(o.coinCount,1);near(o.headsPercent,20);near(o.successPercent,20);
o=S.odds(char,'informatica',{difficulty:0,advantage:1});
near(o.successPercent,100);near(o.criticalSuccessPercent,100);
o=S.odds({skills:{}},'sigilo',{difficulty:10,advantage:1});
near(o.headsPercent,0);near(o.criticalFailurePercent,100);
assert.deepEqual(S.roll(char,'informatica',{difficulty:9,advantage:1,rng:()=>0.1}).coins,['heads','heads']);
assert.equal(S.roll(char,'informatica',{difficulty:9,advantage:1,rng:()=>0.1}).outcome,'critical-success');
assert.equal(S.roll(char,'informatica',{difficulty:9,advantage:1,rng:()=>0.9}).outcome,'critical-failure');
let n=0;assert.equal(S.roll(char,'informatica',{difficulty:9,advantage:1,rng:()=>[0.9,0.1][n++]}).outcome,'success');
assert.equal(S.roll(char,'informatica',{difficulty:9,rng:()=>0.9}).outcome,'failure');
assert.equal(S.roll(char,'informatica',{difficulty:9,rng:()=>0.1}).outcome,'success');
assert.throws(()=>S.roll(char,'inexistente'));
assert.throws(()=>S.odds(char,'informatica',{difficulty:-1}));
assert.throws(()=>S.odds(char,'informatica',{advantage:1.5}));
assert.throws(()=>S.setPoints(char,'informatica',-1));
