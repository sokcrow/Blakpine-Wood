/* Blakpine-Wood: continuidad estructural de sótanos sin duplicar motores. */
(function(root,factory){
 'use strict';
 const api=factory();
 if(typeof module==='object'&&module.exports)module.exports=api;
 if(root)root.FHBasement=api;
})(typeof globalThis!=='undefined'?globalThis:this,function(){
 'use strict';
 const clone=value=>JSON.parse(JSON.stringify(value));
 function groundIndex(map){
  const floors=map?.floors||[];
  if(map?.mainFloorId){const at=floors.findIndex(f=>f.id===map.mainFloorId);if(at>=0)return at;}
  const level=floors.findIndex(f=>Number(f.elevationFt)===0);
  return level>=0?level:0;
 }
 function resolveSlabs(map,slabFor){
  const floors=map?.floors||[],ground=groundIndex(map);
  if(typeof slabFor!=='function')return floors.map(()=>null);
  const base=ground>0?slabFor(ground):null;
  return floors.map((floor,i)=>{
   if(i>=ground)return null;
   const own=slabFor(i);
   // La huella de sótano dibujada explícitamente siempre tiene prioridad.
   // Sin perímetro propio, usar la huella del nivel suelo, no un piso vacío.
   const slab=own?.enabled&&own.spans?.length?own:base;
   return slab?.enabled&&slab.spans?.length?clone(slab):{enabled:false,spans:[],regions:[],micro:1};
  });
 }
 function perimeter(floor){
  return (floor?.items||[]).filter(it=>it.a&&it.b&&(it.type==='red_wall'||
   (it.roofBoundary&&['door','peephole_door','window','opening'].includes(it.type))));
 }
 function expandProject(map){
  if(!map||!Array.isArray(map.floors))return map;
  const ground=groundIndex(map),source=perimeter(map.floors[ground]);
  if(!ground||!source.length)return map;
  // Si la huella principal no está cerrada, no inventar paredes en sótanos.
  if(map.buildingSlabs?.enabled===false)return map;
  for(let i=0;i<ground;i++){
   const floor=map.floors[i],base=(floor.items||[]).filter(it=>it.basementInherited!==true);
   if(base.some(it=>it.type==='red_wall')){floor.items=base;continue;}
   const generated=source.map((it,n)=>({
    id:'fh_basement_'+String(floor.id)+'_'+String(it.id||n),type:'wall',
    a:{x:it.a.x,y:it.a.y},b:{x:it.b.x,y:it.b.y},
    heightFt:Number(floor.ceilingHeightFt)||9,blocksMovement:true,
    autoGenerated:true,basementInherited:true,sourceFloorId:map.floors[ground].id
   }));
   floor.items=[...base,...generated];
  }
  return map;
 }
 return Object.freeze({groundIndex,resolveSlabs,perimeter,expandProject});
});
