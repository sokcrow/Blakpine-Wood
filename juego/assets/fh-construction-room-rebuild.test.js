'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');

// Ejecuta la función original de index.html con geometría de detección fija.
// No copia ni reimplementa la lógica de reconstrucción.
const html=fs.readFileSync(path.resolve(__dirname,'../../index.html'),'utf8');
const start=html.indexOf('function rectOverlap(a,b)');
const end=html.indexOf('// Pared roja:',start);
assert.ok(start>=0&&end>start,'rebuildFloorSpaces disponible en el editor');
const code=html.slice(start,end);

function setup() {
 const original={id:'room_auto_1',roomId:'bano_empleados',label:'Baño empleados',
  type:'room',autoGenerated:true,x:1,y:1,w:2,h:2,
  spans:[{x:1,y:1,w:2,h:2}],constructionRoom:'bano',
  zoneId:'main',apartmentId:'',manualApartmentId:'',surfaceStyle:{preset:'baldosa'}};
 const project={floors:[{id:'f1',items:[original]}]};
 const region={id:0,minX:1,minY:1,maxX:2,maxY:2,
  cells:[11,12,21,22],doorIds:new Set(['door_a'])};
 const sandbox={
  project,spaceCache:[],SEGMENT_TYPES:new Set(['wall']),AREA_TYPES:new Set(['room']),
  detectFloorRegions:()=>({micro:1,W:10,regions:[region],confirmed:[region],
   pending:[],doorRegions:new Map(),doors:[]}),
  roomShapeSpans:()=>[{x:1,y:1,w:2,h:2}],
  numId:()=> 'new_room_unexpected',
  rounded:(n,d=3)=>Number(n.toFixed(d)),
  sanitizeId:s=>s.toLowerCase().replace(/\s+/g,'_'),
  areaHasPoint:(room,p)=>p.x>=room.x&&p.x<room.x+room.w&&p.y>=room.y&&p.y<room.y+room.h,
  roomHasPosition:(room,p)=>p.x>=room.x&&p.x<room.x+room.w&&p.y>=room.y&&p.y<room.y+room.h,
  normalizeArchitecture:()=>{},
  ForestShared:{roomAtSwitchSide:()=>null,switchNormal:()=>({x:1,y:0})}
 };
 vm.createContext(sandbox);
 vm.runInContext(code,sandbox,{filename:'index.html#rebuildFloorSpaces'});
 return {project,sandbox};
}
test('Conserva la clasificación de una habitación generada al guardar',()=>{
 const {project,sandbox}=setup();
 sandbox.rebuildFloorSpaces(0);
 const room=project.floors[0].items[0];
 assert.equal(room.id,'room_auto_1');
 assert.equal(room.roomId,'bano_empleados');
 assert.equal(room.constructionRoom,'bano');
 assert.equal(room.surfaceStyle.preset,'baldosa');
});
test('Exportación/reconstrucción conserva construcción funcional',()=>{
 const {project,sandbox}=setup();
 sandbox.recalcAllSpaces();sandbox.recalcAllSpaces();
 const copied=JSON.parse(JSON.stringify(project));
 assert.equal(copied.floors[0].items[0].constructionRoom,'bano');
 assert.equal(copied.floors[0].items[0].id,'room_auto_1');
});
